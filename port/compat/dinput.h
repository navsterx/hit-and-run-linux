/* Linux stand-in for <dinput.h>: the DirectInput 8 CONSTANTS and DATA STRUCTURES the game uses to name
   input points (DIK_ key codes, DIJOFS_/DIMOFS_ offsets) and to describe force-feedback effects.
   GENERATED by port/gen_dinput.py from libs/pure3d/sdks/dx8/dinput.h. No DirectInput API is provided:
   devices are read by radcore's SDL2 controller backend (radcontroller/linux/sdlcontroller.cpp). */
